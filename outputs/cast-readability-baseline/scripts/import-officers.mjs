import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const project=process.argv[2];
if(!project)throw new Error('用法：node scripts/import-officers.mjs <sango_infinity-main 目录>');
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const paths={common:'Build/Content/Data/Common/PersonLibrary.json',custom:'Build/CustomEdit/CustomPerson.json',biographies:'Build/Content/Language/PersonDescription.json',personalities:'Build/Content/Data/Common/Personalities.json',righteousness:'Build/Content/Data/Common/Argumentations.json'};
const input=Object.fromEntries(await Promise.all(Object.entries(paths).map(async([key,path])=>[key,await readFile(resolve(project,path),'utf8')])));
const biographies=JSON.parse(input.biographies);
const rows=[];
for(const kind of ['common','custom']){
 const library=JSON.parse(input[kind]).PersonLibrary;
 for(const [key,source] of Object.entries(library)){
  if(String(source.Id)!==key||!source.Name)throw new Error('武将编号或姓名无效：'+key);
  for(const stat of ['command','strength','intelligence','politics','glamour'])if(!Number.isInteger(source[stat])||source[stat]<0||source[stat]>100)throw new Error(source.Name+'属性无效：'+stat);
  rows.push({kind,source,biography:kind==='common'?(biographies[source.description]?.cn||''):''});
 }
}
const manifest={sourceProject:'sango_infinity-main',counts:{common:rows.filter(r=>r.kind==='common').length,custom:rows.filter(r=>r.kind==='custom').length,total:rows.length},sources:Object.fromEntries(Object.entries(paths).map(([key,path])=>[key,{path,sha256:createHash('sha256').update(input[key]).digest('hex')}]))};
await mkdir(resolve(root,'data'),{recursive:true});
await writeFile(resolve(root,'data/officers.mjs'),'// Generated by scripts/import-officers.mjs. Preserve source fields verbatim.\nexport const OFFICER_SOURCE = '+JSON.stringify(rows,null,2)+';\n');
await writeFile(resolve(root,'data/officers-source.json'),JSON.stringify(manifest,null,2)+'\n');
const names=(key,table)=>Object.fromEntries(Object.values(JSON.parse(input[key])[table]).map(row=>[row.Id,row.Name]));
await writeFile(resolve(root,'data/officer-traits.mjs'),'// Source labels only; original mechanical modifiers are not applied.\nexport const PERSONALITY_NAMES = '+JSON.stringify(names('personalities','Personalities'),null,2)+';\nexport const RIGHTEOUSNESS_NAMES = '+JSON.stringify(names('righteousness','Argumentations'),null,2)+';\n');
console.log(JSON.stringify(manifest.counts));
