export const PAGE_GUIDE_STORAGE_KEY='sango-page-guides-v1';
export function createGuidePreferences(storage){
 let enabled=true,seen=new Set();
 try{const data=JSON.parse(storage?.getItem(PAGE_GUIDE_STORAGE_KEY)||'null');if(data?.version===1){enabled=data.enabled!==false;seen=new Set((Array.isArray(data.seen)?data.seen:[]).filter(id=>Object.hasOwn(PAGE_GUIDES,id)));}}catch{}
 const persist=()=>{try{storage?.setItem(PAGE_GUIDE_STORAGE_KEY,JSON.stringify({version:1,enabled,seen:[...seen]}));return true;}catch{return false;}};
 return {
  get enabled(){return enabled;},
  shouldShow:id=>enabled&&Object.hasOwn(PAGE_GUIDES,id)&&!seen.has(id),
  hasSeen:id=>seen.has(id),
  dismiss(id){if(Object.hasOwn(PAGE_GUIDES,id))seen.add(id);return persist();},
  setEnabled(value){enabled=!!value;return persist();},
  reset(){seen.clear();enabled=true;return persist();}
 };
}
