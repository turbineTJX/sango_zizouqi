import {createRequire} from 'node:module';
import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createScenario} from '../scenarios.mjs';
import {lockDeployment,validateSave} from '../engine.mjs';
import {hasTrait} from '../officer-traits.mjs';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'4196'},stdio:'pipe',windowsHide:true});
let browser;
try{
 await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(Error('Server exited '+code)));});
 const state=createScenario('tactical-shu-defense'),b=state.battle,u=b.sides[0].units.find(u=>hasTrait(u,'formationSupport')),ally=b.sides[0].units[0];
 const positions=[[3,3],[4,3],[4,4],[3,4],[4,2],[2,3]];b.sides[0].units.forEach((u,i)=>{[u.x,u.y]=positions[i];});Object.assign(u,{x:2,y:2});Object.assign(ally,{x:3,y:2});lockDeployment(b);validateSave(structuredClone(state));
 browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(state=>localStorage.setItem('sango-historical-battle-v1',JSON.stringify(state)),state);
 await page.goto('http://127.0.0.1:4196/#historical-battle');
 await page.locator(`[data-unit="${u.id}"]`).click({button:'right'});
 assert.match(await page.locator('.modal').innerText(),/戟兵/);
 assert.equal(await page.locator('.modal [data-skill="passage"]').count(),0);
 assert.match(await page.locator('.modal').innerText(),/营务威力/);

 await page.locator('.modal [data-action="unit-officer"]').click();
 await page.locator('.passive-skill').filter({hasText:'协阵'}).locator('summary').click();
 assert.match(await page.locator('.modal').innerText(),/相邻其他友军/);
 assert.match(await page.locator('.modal').innerText(),/不占战法/);
 await mkdir('outputs/auxiliary-ui',{recursive:true});
 await page.screenshot({path:'outputs/auxiliary-ui/aura.png',fullPage:true,animations:'disabled'});
 await page.locator('.modal [data-action="unit-stats"]').click();
 await page.locator('#inspect-unit').selectOption(ally.id);
 const aura=page.locator('[data-status="formationAura"]');await aura.click();
 assert.match(await aura.innerText(),/简雍/);assert.match(await aura.innerText(),/不提高攻防/);
 await aura.scrollIntoViewIfNeeded();
 await page.screenshot({path:'outputs/auxiliary-ui/received.png',fullPage:true,animations:'disabled'});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'outputs/auxiliary-ui/mobile.png',fullPage:true,animations:'disabled'});
 assert.deepEqual(errors,[]);
 await writeFile('outputs/auxiliary-ui/result.json',JSON.stringify({passed:true,errors},null,2));
 console.log('Officer aura UI passed: fixed traits, no aura tactic slot, political power, received aura and mobile layout.');
}finally{await browser?.close();server.kill();}
