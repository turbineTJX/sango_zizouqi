import {createRequire} from 'node:module';
import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createScenario} from '../scenarios.mjs';
import {lockDeployment,stepBattle,validateSave} from '../engine.mjs';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'4298'},stdio:'pipe',windowsHide:true});
let browser;const out='outputs/roster-layout';await mkdir(out,{recursive:true});
try{
 await new Promise((ok,no)=>{server.stdout.once('data',ok);server.once('error',no);server.once('exit',c=>no(Error('server '+c)));});
 browser=await chromium.launch({channel:'msedge',headless:true});
 const errors=[],page=await browser.newPage({viewport:{width:1440,height:1000}});page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4298');await page.locator('[data-action="campaign-lobby"]').click();await page.locator('[data-action="launch-history"]').click();
 await page.locator('.unit-nameplate').first().waitFor();await page.waitForTimeout(700);
 const unitId=await page.locator('.unit-nameplate.side-0').first().getAttribute('data-inspect');
 await page.locator(`.unit-nameplate[data-inspect="${unitId}"]`).click();
 assert.match(await page.locator('#modal-title').innerText(),/部队属性/);
 assert.equal(await page.locator('#inspect-unit').inputValue(),unitId);
 await page.screenshot({path:out+'/desktop-inspection.png'});
 await page.locator('.close-button').click();
 await page.locator(`[data-unit="${unitId}"]`).click();assert.equal(await page.locator('.deploy-selected.battle-unit').count(),1);
 await page.screenshot({path:out+'/desktop-deployment.png'});
 // Real combat snapshot exercises dense contact and deterministic save loading.
 const state=createScenario('field',83);lockDeployment(state.battle);for(let i=0;i<20;i++)stepBattle(state.battle);validateSave(structuredClone(state));
 const dense=await browser.newPage({viewport:{width:1440,height:1000}});dense.on('pageerror',e=>errors.push(e.message));
 await dense.addInitScript(s=>localStorage.setItem('sango-battle-lab-v1',JSON.stringify(s)),state);
 await dense.goto('http://127.0.0.1:4298/#battle-lab');await dense.locator('.unit-nameplate').first().waitFor();await dense.waitForTimeout(700);
 const overlap=await dense.evaluate(()=>{const labels=[...document.querySelectorAll('.unit-nameplate')].map(e=>e.getBoundingClientRect());let count=0;for(let i=0;i<labels.length;i++)for(let j=i+1;j<labels.length;j++){const a=labels[i],b=labels[j];if(Math.min(a.right,b.right)-Math.max(a.left,b.left)>1&&Math.min(a.bottom,b.bottom)-Math.max(a.top,b.top)>1)count++;}return count;});
 assert.equal(overlap,0,'roster cards must not overlap');
 assert.equal(await dense.locator('.unit-nameplate').count(),await dense.locator('[data-unit]').count(),'one portrait per live unit');
 assert.equal(await dense.locator('#battle-board .unit-nameplate,#battle-label-lines').count(),0,'portrait cards and tethers no longer cover the map');
 await dense.locator('.unit-nameplate').first().hover();assert.equal(await dense.locator('.battle-unit.roster-highlight').count(),1);
 await dense.screenshot({path:out+'/desktop-contact.png'});
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});mobile.on('pageerror',e=>errors.push(e.message));
 await mobile.addInitScript(s=>localStorage.setItem('sango-battle-lab-v1',JSON.stringify(s)),state);
 await mobile.goto('http://127.0.0.1:4298/#battle-lab');await mobile.locator('.unit-nameplate').first().waitFor();
 const label=mobile.locator('.unit-nameplate.side-1').first();await label.scrollIntoViewIfNeeded();
 const scrollBefore=await mobile.locator('.arena-stage').evaluate(el=>el.scrollLeft);
 assert.ok((await label.boundingBox()).height>=44);await mobile.screenshot({path:out+'/mobile-map.png'});
 await label.tap();assert.match(await mobile.locator('#modal-title').innerText(),/部队属性/);
 assert.equal(await mobile.locator('#inspect-unit').inputValue(),await label.getAttribute('data-inspect'));
 await mobile.waitForTimeout(250);
 const sheet=await mobile.locator('.modal').boundingBox();assert.ok(sheet.y>200&&sheet.y+sheet.height<=845,JSON.stringify(sheet));
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await mobile.screenshot({path:out+'/mobile-inspection.png'});
 await mobile.locator('[data-action="unit-officer"]').tap();assert.match(await mobile.locator('#modal-title').innerText(),/武将属性/);
 await mobile.locator('.close-button').tap();assert.equal(await mobile.locator('.modal').count(),0);
 assert.equal(await mobile.locator('.arena-stage').evaluate(el=>el.scrollLeft),scrollBefore,'closing details preserves the mobile map position');
 await mobile.setViewportSize({width:844,height:390});await mobile.waitForTimeout(250);
 const stageBox=await mobile.locator('.arena-stage').boundingBox();assert.ok(stageBox.height>=130,'landscape retains map height: '+stageBox.height);
 await mobile.screenshot({path:out+'/mobile-landscape.png'});
 await dense.evaluate(()=>localStorage.setItem('sango-art-mode','builtin'));await dense.reload();await dense.locator('.unit-nameplate').first().waitFor();
 await dense.screenshot({path:out+'/builtin-contact.png'});
 assert.deepEqual(errors,[]);await writeFile(out+'/ui-result.json',JSON.stringify({overlap,mobileTouch:true,deployment:true,errors},null,2));
 console.log('PASS: faction rosters, dense contact, deployment, desktop details, mobile tap/bottom sheet and builtin fallback');
}finally{await browser?.close();server.kill();}
