import {createRequire} from 'node:module';
import {spawn} from 'node:child_process';
import {mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'4191'},stdio:'pipe',windowsHide:true});
let browser;
try {
  await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(new Error(`Server exited: ${code}`)));});
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const action=name=>page.locator(`[data-action="${name}"]`);
  await page.goto('http://127.0.0.1:4191');
  await page.locator('.mode-selection').waitFor();
  assert.equal(await page.locator('.mode-card').count(),2);
  assert.equal(await page.locator('.historical-card').count(),0);
  await mkdir('outputs/mode-entry',{recursive:true});
  await page.screenshot({path:'outputs/mode-entry/desktop.png',fullPage:true});
  await action('strategy').click();await page.locator('.national-scenario-list').waitFor();await action('continue-national').click();await page.locator('.strategy-page').waitFor();
  await action('lobby').first().click();await page.locator('.mode-selection').waitFor();
  const strategy=await page.evaluate(()=>localStorage.getItem('sango-sovereign-v2'));
  await action('campaign-lobby').click();await page.locator('.historical-card').first().waitFor();
  await action('launch-history').click();await page.locator('#battle-board').waitFor();
  await action('lobby').first().click();await page.locator('.mode-selection').waitFor();
  const history=await page.evaluate(()=>localStorage.getItem('sango-historical-battle-v1'));
  await action('strategy').click();await page.locator('.national-scenario-list').waitFor();await action('continue-national').click();await page.locator('.strategy-page').waitFor();
  assert.equal(await page.evaluate(()=>localStorage.getItem('sango-sovereign-v2')),strategy);
  await action('lobby').first().click();await action('campaign-lobby').click();
  await action('continue-history').click();await page.locator('#battle-board').waitFor();
  assert.equal(await page.evaluate(()=>localStorage.getItem('sango-historical-battle-v1')),history);
  await page.reload();await page.locator('#battle-board').waitFor();
  await action('lobby').first().click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'outputs/mode-entry/mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await action('campaign-lobby').click();await page.locator('.historical-card').first().waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await action('lobby').first().click();await page.reload();await page.locator('.mode-selection').waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: unified entry, both modes, independent saves, battle reload and mobile layout');
} finally {await browser?.close();server.kill();}
