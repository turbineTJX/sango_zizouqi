import {createRequire} from 'node:module';
import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createScenario} from '../scenarios.mjs';
import {lockDeployment,stepBattle,validateSave,COMMAND_RESOURCE,battleStratagems} from '../engine.mjs';
import {STRATAGEMS,selectStratagemSource,stratagemEffectText} from '../stratagems.mjs';
const require=createRequire(import.meta.url),{chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'4329'},stdio:'pipe',windowsHide:true});
let browser;
try{
 await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(Error('Server exited '+code)));});
 const unit=(id,type='spear')=>({id,type,troops:3000,level:5});
 const state=createScenario('custom-battle',4511,20,null,{seed:4511,terrain:'land',ownTeam:[unit('cao'),unit('jia','crossbow'),unit('yu','halberd')],enemyTeam:[unit('shao'),unit('wen'),unit('yan')],ownTeamRoles:{leader:'cao',advisor:'yu'}});
 lockDeployment(state.battle);while(!state.battle.result&&state.battle.commandProgress<COMMAND_RESOURCE.capacity)stepBattle(state.battle);
 assert.equal(state.battle.result,null);assert.equal(state.battle.commandProgress,COMMAND_RESOURCE.capacity);validateSave(state);
 const keys=battleStratagems(state.battle),errors=[];
 browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(data=>{if(!localStorage.getItem('sango-historical-battle-v1'))localStorage.setItem('sango-historical-battle-v1',JSON.stringify(data));},state);
 await page.goto('http://127.0.0.1:4329/#historical-battle');
 await page.locator('#command-cue').click();
 const dialog=page.getByRole('dialog',{name:'选择军略'});await dialog.waitFor();
 assert.equal(await dialog.locator('[data-action="command-category"]').count(),0);
 assert.equal(await dialog.locator('.stratagem-options [data-command]').count(),keys.length);
 for(const key of keys){const text=await dialog.locator(`[data-command="${key}"]`).innerText();assert.ok(text.includes(STRATAGEMS[key].name));assert.ok(text.includes(stratagemEffectText(selectStratagemSource(state.battle.sides[0].commanders,key))));}
 await mkdir('outputs/stratagem-picker-ui',{recursive:true});
 await page.screenshot({path:'outputs/stratagem-picker-ui/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.ok(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth));
 await page.screenshot({path:'outputs/stratagem-picker-ui/mobile.png',fullPage:true});
 await dialog.getByRole('button',{name:'取消',exact:true}).click();
 const read=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('sango-historical-battle-v1')));
 assert.deepEqual((await read()).battle,state.battle);
 await page.locator('#command-cue').click();
 await dialog.locator('[data-command="cao-wuchao"]').click();
 await dialog.waitFor({state:'detached'});
 const saved=await read();assert.equal(saved.battle.commandProgress,0);assert.equal(saved.battle.tick,state.battle.tick);assert.equal(saved.battle.lastCommand.key,'cao-wuchao');validateSave(saved);
 await page.reload();await page.locator('#command-cue').click();
 assert.ok(await dialog.locator('[data-command="cao-wuchao"]').isDisabled());
 assert.deepEqual((await read()).battle,saved.battle);
 const emptyState=createScenario('custom-battle',4511,20,null,{seed:4511,terrain:'land',ownTeam:[unit('person-472'),unit('chu')],enemyTeam:[unit('shao')],ownTeamRoles:{leader:'person-472',advisor:'chu'}});
 const emptyPage=await browser.newPage({viewport:{width:390,height:844}});emptyPage.on('pageerror',e=>errors.push(e.message));
 await emptyPage.addInitScript(data=>localStorage.setItem('sango-historical-battle-v1',JSON.stringify(data)),emptyState);
 await emptyPage.goto('http://127.0.0.1:4329/#historical-battle');await emptyPage.locator('#command-cue').click();
 const emptyDialog=emptyPage.getByRole('dialog',{name:'选择军略'});
 assert.equal(await emptyDialog.locator('.stratagem-options [data-command]').count(),0);
 assert.ok((await emptyDialog.innerText()).includes('暂无可用军略'));
 assert.equal(await emptyDialog.locator('[data-command="retreat"]').count(),1);
 assert.deepEqual(errors,[]);
 await writeFile('outputs/stratagem-picker-ui/result.json',JSON.stringify({keys,desktop:true,mobile:true,cancelPreservesBattle:true,oneClickCast:true,reloadPreservesBattle:true,noProvider:true,errors},null,2));
 console.log('Stratagem picker desktop/mobile, cancellation, one-click cast and reload passed.');
}finally{await browser?.close();server.kill();}
