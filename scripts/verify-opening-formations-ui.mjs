import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
import {generateBattle} from '../battle-generator.mjs';
import {deployBattleUnit} from '../battle-deployment.mjs';
import {formationCells} from '../bond-battlefield.mjs';
import {OFFICER_CATALOG} from '../officer-catalog.mjs';
const id=name=>OFFICER_CATALOG.find(u=>u.name===name).id;
const own=['周瑜','黄盖','陈群','程武','秦宓','吾粲'],enemy=['袁绍','颜良','文丑','张郃','沮授','田丰'];
const team=names=>names.map(name=>({id:id(name),type:'archer',troops:3000,level:10}));
const state=generateBattle({seed:20261028,terrain:'land',mapId:'plain-open',battleKind:'field',ownTeam:team(own),enemyTeam:team(enemy),events:[],shieldPercent:0});
const marks=formationCells(state.battle,0,'bondDragonFormation');
for(let i=0;i<3;i++)assert.equal(deployBattleUnit(state.battle,id(own[i]),marks[i].x,marks[i].y),null);
const out=process.argv.find(a=>a.startsWith('--out='))?.slice(6)||'work/opening-formations-trial/ui',port=4323;await mkdir(out,{recursive:true});
const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:String(port)},stdio:'pipe',windowsHide:true});let browser;
try{
 await new Promise((ok,no)=>{server.stdout.once('data',ok);server.once('error',no);server.once('exit',code=>no(Error('server '+code)));});
 browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1600,height:1000},serviceWorkers:'block'}),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>localStorage.setItem('sango-page-guides-v1',JSON.stringify({version:1,enabled:false,seen:[]})));
 await page.goto('http://127.0.0.1:'+port);
 await page.evaluate(async()=>{const {BattleEffects}=await import('./battle-effects.mjs'),original=BattleEffects.prototype.update;BattleEffects.prototype.update=function(b,options){window.actualFormationBattle=b;return original.call(this,b,options);};});
 await page.locator('[data-action="settings"]').first().click();
 await page.locator('#import-file').setInputFiles({name:'opening-formation.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(state))});
 await page.locator('#battle-board').waitFor();
 assert.equal(await page.locator('[data-formation-id="bondDragonFormation"][data-formation-side="0"]').count(),3);
 assert.equal(await page.locator('[data-formation-id="bondGuard"][data-formation-side="0"]').count(),0);
 assert.equal(await page.locator('#battle-bonds [data-bond="bondDragonFormation"].bond-lit').count(),1);
 assert.equal(await page.locator('#battle-bonds [data-bond="bondGuard"].bond-lit').count(),0);
 assert.match(await page.locator('[data-formation-id="bondDragonFormation"]').first().textContent(),/龙首位|镇军位|翔翼位/);
 await page.screenshot({path:out+'/desktop-deployment.png'});
 await page.locator('[data-action="pause"]').first().click();
 await page.waitForFunction(()=>window.actualFormationBattle?.deploymentLocked);
 const evidence=await page.evaluate(()=>({tick:actualFormationBattle.tick,choice:actualFormationBattle.sides[0].bondFormationChoice,receipts:actualFormationBattle.sides[0].units.map(u=>({name:u.name,entries:u.bondOpeningFormations,shields:u.statuses?.shield?.layers.filter(l=>l.source.startsWith('formation:'))||[]}))}));
 assert.equal(evidence.choice.id,'bondDragonFormation');assert.equal(evidence.receipts.find(u=>u.name==='周瑜').entries.length,1);
 assert.ok(evidence.receipts.every(u=>u.shields.length===1&&u.shields[0].label==='龙飞 · 成阵护盾'));
 if((await page.locator('[data-action="pause"]').first().innerText()).includes('暂停'))await page.locator('[data-action="pause"]').first().click();
 await page.screenshot({path:out+'/desktop-active.png'});
 await page.locator('#battle-bonds [data-bond="bondDragonFormation"]').click();
 assert.match(await page.locator('.text-detail-view').innerText(),/成阵|三位齐备/);await page.screenshot({path:out+'/details.png'});await page.keyboard.press('Escape');
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:out+'/mobile.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
 assert.deepEqual(errors,[]);await writeFile(out+'/result.json',JSON.stringify({passed:true,evidence,errors},null,2));
 console.log('PASS actual save import, unique formation markers/highlight, real opening receipts, desktop/mobile and effect details');
}finally{await browser?.close();server.kill();}
