import {createRequire} from 'node:module';
import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createScenario} from '../scenarios.mjs';
import {recommendedTacticIds} from '../tactics.mjs';
const require=createRequire(import.meta.url),{chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'4211'},stdio:'pipe',windowsHide:true});
let browser;
try{
 await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(Error('Server exited '+code)));});
 const unit=(id,type,troops)=>({id,type,troops,level:5});
 const state=createScenario('custom-battle',73000009,20,null,{seed:73000009,terrain:'land',ownTeam:[unit('person-396','cavalry',6000),unit('person-646','spear',1500),unit('person-123','logistics',1500)],enemyTeam:[unit('jin','spear',3000),unit('yuanxia','archer',3000),unit('person-610','crossbow',3000)]});
 browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(data=>{if(!localStorage.getItem('sango-historical-battle-v1'))localStorage.setItem('sango-historical-battle-v1',JSON.stringify(data));},state);
 await page.goto('http://127.0.0.1:4211/#historical-battle');
 await page.locator('[data-action="loadout"]').first().click();
 await page.locator('#loadout-unit').selectOption('person-396');
 await page.getByText('快速配置 · 选择定位',{exact:true}).click();
 await page.locator('[data-preset="assault"]').click();
 await page.getByText('快速配置 · 选择定位',{exact:true}).click();
 await page.getByRole('button',{name:'采用专属搭配',exact:true}).click();
 const slots=()=>page.locator('[data-tactic-slot]').evaluateAll(els=>els.map(e=>e.value));
 assert.deepEqual(await slots(),recommendedTacticIds(state.battle.sides[0].units[0]));
 await page.getByText('快速配置 · 选择定位',{exact:true}).click();
 await mkdir('outputs/balance-objectives-ui',{recursive:true});
 await page.screenshot({path:'outputs/balance-objectives-ui/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'outputs/balance-objectives-ui/mobile.png',fullPage:true});
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('sango-historical-battle-v1')));
 assert.deepEqual(saved.battle.sides[0].units[0].tactics,recommendedTacticIds(state.battle.sides[0].units[0]));
 await page.reload();await page.locator('[data-action="loadout"]').first().click();
 await page.locator('#loadout-unit').selectOption('person-396');
 assert.deepEqual(await slots(),recommendedTacticIds(state.battle.sides[0].units[0]));
 assert.deepEqual(errors,[]);
 await writeFile('outputs/balance-objectives-ui/result.json',JSON.stringify({passed:true,checks:['普通预设切换后恢复专属搭配','三槽顺序与实际保存一致','刷新后保留','桌面与移动布局','无浏览器脚本错误'],tactics:await slots()},null,2));
 console.log('PASS: 专属搭配点击、保存、刷新，桌面与手机布局');
}finally{await browser?.close();server.kill();}
